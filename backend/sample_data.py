def _build(rows: list[tuple]) -> list[dict]:
    """Собрать задачи с id и связями по id. Дат не задаёт — их считает recalculate."""
    ids = {}
    tasks = []
    for number, (name, description, assignee, duration, predecessors) in enumerate(rows, 1):
        ids[name] = number
        tasks.append({"id": number, "name": name, "description": description,
                      "assignee": assignee, "duration": duration,
                      "predecessors": [ids[p] for p in predecessors],
                      "not_earlier_than": None})
    return tasks


def sample_tasks() -> list[dict]:
    """План, которым наполняется страница при старте."""
    return _build(SAMPLE)


def demo_tasks() -> list[dict]:
    """План для демонстрационного файла Excel."""
    return _build(DEMO)
